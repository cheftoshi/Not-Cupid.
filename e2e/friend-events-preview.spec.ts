import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('local shared discovery: filters, review, reset, failures and access', async ({page}, testInfo) => {
  const writes:string[]=[];
  page.on('request',r=>{if(r.method()==='POST' && r.url().includes('/api/friend'))writes.push(r.url());});
  await page.addInitScript(() => {localStorage.setItem('nc_pwa_install_dismissed',String(Date.now()));localStorage.setItem('nc_pwa_push_dismissed',String(Date.now()));});
  // Loopback HTTP only: WebKit otherwise upgrades scripts to nonexistent local TLS.
  if(testInfo.project.name==='iphone-webkit') await page.route('**/review/friend-events', async route => { const response=await route.fetch(); const headers=response.headers(); if(headers['content-security-policy']) headers['content-security-policy']=headers['content-security-policy'].replace('upgrade-insecure-requests',''); await route.fulfill({response,headers}); });
  await page.goto('/review/friend-events');
  await expect(page.locator('main')).toHaveAttribute('data-preview-ready','true',{timeout:20000});
  await expect(page.getByRole('heading',{name:'Good plans. New friends.'})).toBeVisible();
  await expect(page.getByRole('article')).toHaveCount(6);
  await page.getByText('Playground controls',{exact:true}).click();
  await page.getByLabel('What',{exact:true}).selectOption('music');
  await expect(page.getByRole('article')).toHaveCount(3);
  await page.getByLabel('Listed as free',{exact:true}).check();
  await expect(page.getByRole('article')).toHaveCount(1);
  await page.getByRole('button',{name:'Find people to go with'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button',{name:'Find people to go with'})).toBeFocused();
  await page.getByRole('button',{name:'Find people to go with'}).click();
  await page.getByRole('button',{name:'Save mock invitation'}).dblclick();
  await expect(page.getByRole('heading',{name:'Mock invitation saved'})).toBeVisible();
  await page.getByRole('button',{name:'Back to events'}).click();
  await expect(page.getByRole('button',{name:'Open your plan & chat'})).toHaveCount(1);
  await page.getByRole('button',{name:'Reset filters'}).click();
  await page.getByRole('button',{name:/View Sample/}).click();
  await expect(page.getByRole('heading',{name:'Sample invitation'})).toBeVisible();
  await page.getByRole('button',{name:'Close review'}).click();
  await page.getByLabel('Event or venue').fill('no match');
  await expect(page.getByRole('heading',{name:'No events match these filters'})).toBeVisible();
  await page.getByRole('button',{name:'Show all ideas'}).click();
  await page.getByRole('button',{name:/Show more ideas/}).click();
  await expect(page.getByRole('article')).toHaveCount(7);
  await page.getByLabel('Test state').selectOption('unavailable');
  await expect(page.getByRole('article')).toHaveCount(0);
  await page.getByRole('button',{name:'Retry events'}).click();
  await expect(page.getByRole('article')).toHaveCount(7);
  await page.getByLabel('Test state').selectOption('loading');
  await expect(page.getByRole('article')).toHaveCount(0);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByLabel('Test state').selectOption('empty');
  await expect(page.getByRole('heading',{name:'No events match these filters'})).toBeVisible();
  await page.getByRole('button',{name:'Reset playground'}).click();
  const violations=(await new AxeBuilder({page}).include('main').analyze()).violations;
  expect(violations).toEqual([]);
  await page.screenshot({path:`artifacts/friend-events/${testInfo.project.name}-light.png`,fullPage:true});
  await page.getByRole('button',{name:'Toggle theme'}).click();
  await page.waitForTimeout(500); // Let existing app theme color transitions settle before contrast sampling.
  expect((await new AxeBuilder({page}).include('main').analyze()).violations).toEqual([]);
  await page.screenshot({path:`artifacts/friend-events/${testInfo.project.name}-dark.png`,fullPage:true});
  await page.setViewportSize({width:320,height:800});
  await page.evaluate(()=>document.documentElement.style.fontSize='200%');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`artifacts/friend-events/${testInfo.project.name}-200percent.png`,fullPage:true});
  await page.getByRole('button',{name:'Close discovery'}).click();
  await page.getByRole('button',{name:'Open event discovery'}).click();
  await expect(page.getByRole('heading',{name:'Good plans. New friends.'})).toBeVisible();
  expect(writes).toEqual([]);
});
